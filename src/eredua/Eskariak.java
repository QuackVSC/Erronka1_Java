package eredua;

public class Eskariak {

	private Integer zenbakia;
	private String produktua;
	private Double kopurua;
	public Integer getZenbakia() {
		return zenbakia;
	}
	public void setZenbakia(Integer zenbakia) {
		this.zenbakia = zenbakia;
	}
	public String getProduktua() {
		return produktua;
	}
	public void setProduktua(String produktua) {
		this.produktua = produktua;
	}
	public Double getKopurua() {
		return kopurua;
	}
	public void setKopurua(Double kopurua) {
		this.kopurua = kopurua;
	}
	
	
}
